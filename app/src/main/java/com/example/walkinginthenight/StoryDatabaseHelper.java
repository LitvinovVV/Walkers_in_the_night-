    private static final String DATABASE_NAME = "walking_trilogy_quest.db";
    private static final int DATABASE_VERSION = 6;

    public static final String TABLE_SCENES = "scenes";
    public static final String COL_SCENE_ID = "scene_id";
    public static final String COL_BOOK_ID = "book_id";
    public static final String COL_CHAPTER_TITLE = "chapter_title";
    public static final String COL_STORY_TEXT = "story_text";
    public static final String COL_IS_CHAPTER_START = "is_chapter_start";

    public static final String TABLE_CHOICES = "choices";
    public static final String COL_CHOICE_ID = "choice_id";
    public static final String COL_FROM_SCENE = "from_scene_id";
    public static final String COL_CHOICE_TEXT = "choice_text";
    public static final String COL_NEXT_SCENE = "next_scene_id";

    public StoryDatabaseHelper(Context context) {
        super(context, DATABASE_NAME, null, DATABASE_VERSION);
    }

    @Override
    public void onCreate(SQLiteDatabase db) {
        db.execSQL("CREATE TABLE " + TABLE_SCENES + " (" +
                COL_SCENE_ID + " INTEGER PRIMARY KEY, " +
                COL_BOOK_ID + " INTEGER, " +
                COL_CHAPTER_TITLE + " TEXT, " +
                COL_STORY_TEXT + " TEXT, " +
                COL_IS_CHAPTER_START + " INTEGER)");

        db.execSQL("CREATE TABLE " + TABLE_CHOICES + " (" +
                COL_CHOICE_ID + " INTEGER PRIMARY KEY AUTOINCREMENT, " +
                COL_FROM_SCENE + " INTEGER, " +
                COL_CHOICE_TEXT + " TEXT, " +
                COL_NEXT_SCENE + " INTEGER)");

        seedFullTrilogy(db);
    }

    @Override
    public void onUpgrade(SQLiteDatabase db, int oldVersion, int newVersion) {
        db.execSQL("DROP TABLE IF EXISTS " + TABLE_CHOICES);
        db.execSQL("DROP TABLE IF EXISTS " + TABLE_SCENES);
        onCreate(db);
    }

    private void addScene(SQLiteDatabase db, int id, int bookId, String title, String text, boolean isChapterStart) {
        ContentValues cv = new ContentValues();
        cv.put(COL_SCENE_ID, id);
        cv.put(COL_BOOK_ID, bookId);
        cv.put(COL_CHAPTER_TITLE, title);
        cv.put(COL_STORY_TEXT, text);
        cv.put(COL_IS_CHAPTER_START, isChapterStart ? 1 : 0);
        db.insert(TABLE_SCENES, null, cv);
    }

    private void addChoice(SQLiteDatabase db, int fromScene, String text, int nextScene) {
        ContentValues cv = new ContentValues();
        cv.put(COL_FROM_SCENE, fromScene);
        cv.put(COL_CHOICE_TEXT, text);
        cv.put(COL_NEXT_SCENE, nextScene);
        db.insert(TABLE_CHOICES, null, cv);
    }

