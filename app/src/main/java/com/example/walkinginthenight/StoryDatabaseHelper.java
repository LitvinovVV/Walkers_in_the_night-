    public Cursor getScene(int sceneId) {
        SQLiteDatabase db = this.getReadableDatabase();
        return db.rawQuery("SELECT * FROM " + TABLE_SCENES + " WHERE " + COL_SCENE_ID + " = ?",
                new String[]{String.valueOf(sceneId)});
    }

    public Cursor getChoicesForScene(int sceneId) {
        SQLiteDatabase db = this.getReadableDatabase();
        return db.rawQuery("SELECT * FROM " + TABLE_CHOICES + " WHERE " + COL_FROM_SCENE + " = ?",
                new String[]{String.valueOf(sceneId)});
    }

    public Cursor getChaptersByBook(int bookId) {
        SQLiteDatabase db = this.getReadableDatabase();
        return db.rawQuery("SELECT * FROM " + TABLE_SCENES +
                        " WHERE " + COL_BOOK_ID + " = ? AND " + COL_IS_CHAPTER_START + " = 1" +
                        " ORDER BY " + COL_SCENE_ID + " ASC",
                new String[]{String.valueOf(bookId)});
    }
